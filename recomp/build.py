"""Build the recompiled game: work/recomp/*.c + runtime/src/*.c + musl's math -> work/build/yw4.exe.

    python -m recomp.build           compile what changed, link
    python -m recomp.build --run     ... then run it on work/exefs/ (main.bin, sdk.bin)

Uses [tools] cc (Clang recommended, decision 0007) with -O2. Objects go to
work/build/obj/; a source is recompiled when it, or any header, is newer than its object.
The executable is built from the game's code, so it stays in work/ (never commit or share).
"""

from __future__ import annotations

import argparse
import concurrent.futures
import os
import subprocess
import sys
import time
import tomllib
from pathlib import Path

import shutil

from tools.yw4 import config, deps, progress

from . import check

RUNTIME = check.REPO / "runtime"
CFLAGS = ["-std=c11", "-O2", "-ffp-contract=off", "-Wall", "-Wno-unused-label"]
# The runtime's few C++ files (NVIDIA Streamline's headers are C++): no exceptions or RTTI, so no C++ runtime library
CXXFLAGS = ["-std=c++17", "-O2", "-ffp-contract=off", "-Wall", "-fno-exceptions", "-fno-rtti"]
if sys.platform != "win32":
    # glibc under -std=c11 hides what is POSIX and not ISO C (localtime_r, realpath, setenv, fseeko, off_t, S_IFDIR,
    # ftruncate, strnlen...): 13 runtime files failed on Linux without this (2026-11-12). MinGW shows them anyway.
    CFLAGS.append("-D_GNU_SOURCE")
target_flags = check.target_flags  # the host CPU (decision 0034); musl keeps its verified flags

# musl 1.1.19's math (third_party/musl, decision 0013). These are the flags its results were
# verified with against the sdk (tools/yw4/sdkref.py --check uses this same list): no FMA
# contraction, no builtins (the host must not constant-fold with its own libm).
MUSL = check.REPO / "third_party" / "musl"
MUSL_CFLAGS = ["-std=c99", "-O2", "-ffp-contract=off", "-fno-builtin", "-frounding-math",
               "-include", str(MUSL / "yw4" / "glue.h"), f"-I{MUSL / 'yw4'}", f"-I{MUSL / 'src' / 'internal'}"]


def musl_sources() -> list[Path]:
    return sorted((MUSL / "src" / "math").glob("*.c"))


def sources(cfg: config.Config) -> list[Path]:
    gen = cfg.work_dir / "recomp"
    return (sorted(gen.glob("*.c")) + sorted((RUNTIME / "src").glob("*.c")) + sorted((RUNTIME / "src").glob("*.cpp"))
            + musl_sources())


def version_source(cfg: config.Config) -> Path:
    """<work_dir>/build/version.c: which build this is (decision 0047), rewritten only when it changes so a
    build of the same commit relinks nothing new. The number is the repo's VERSION file; the commit is git's
    (+dirty with uncommitted changes to tracked files), else a COMMIT file (a release download has no git),
    else "unknown"."""
    repo = check.REPO
    version = (repo / "VERSION").read_text().strip()
    commit = "unknown"
    try:
        run = lambda *a: subprocess.run(["git", "-C", str(repo), *a], capture_output=True, text=True, check=True).stdout
        commit = run("rev-parse", "--short=7", "HEAD").strip()
        if run("status", "--porcelain", "--untracked-files=no").strip():
            commit += "+dirty"
    except (OSError, subprocess.CalledProcessError):
        if (repo / "COMMIT").is_file():
            commit = (repo / "COMMIT").read_text().strip() or "unknown"
    day = time.strftime("%Y-%m-%d", time.gmtime())
    text = ("/* Generated by recomp.build (decision 0047). */\n"
            f'const char yw4_version[] = "{version}";\n'
            f'const char yw4_git_commit[] = "{commit}";\n'
            f'const char yw4_build_date[] = "{day}";\n')
    src = cfg.work_dir / "build" / "version.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    if not src.is_file() or src.read_text() != text:
        src.write_text(text)
    print(f"YW4 Recomp {version} ({commit}, {day})")
    return src


def dlc_source(cfg: config.Config) -> Path:
    """<work_dir>/build/dlc_known.c: target.toml's [dlc] table, the add-ons the game unlocks when it finds their
    content NCA on boot (decision 0049; runtime/src/svc_misc.c). Rewritten only when it changes."""
    table = tomllib.loads((check.REPO / "target.toml").read_text()).get("dlc", {})
    rows = "".join(f'    {{{int(i)}, "{h.lower()}"}},\n' for i, h in sorted(table.items(), key=lambda kv: int(kv[0])))
    rows = rows or '    {0, ""},\n'  # C needs one element
    text = ("/* Generated by recomp.build from target.toml [dlc] (decision 0049). */\n#include <stddef.h>\n"
            f'#include "{(RUNTIME / "src" / "dlc_known.h").as_posix()}"\n'
            "const Yw4DlcKnown yw4_dlc_known[] = {\n" + rows + "};\n"
            f"const size_t yw4_ndlc_known = {len(table)};\n")
    src = cfg.work_dir / "build" / "dlc_known.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    if not src.is_file() or src.read_text() != text:
        src.write_text(text)
    return src


def newest_header(cfg: config.Config) -> float:
    headers = list((RUNTIME / "include").glob("*.h")) + list((cfg.work_dir / "recomp").glob("*.h"))
    return max(h.stat().st_mtime for h in headers)


# What generated code includes: funcs.h -> yw4rt.h -> yw4cpu.h -> yw4fp.h, and yw4load.h for
# image_info.c only. Other runtime headers changing doesn't rebuild the ~150 generated files.
GENERATED_HEADERS = ("yw4rt.h", "yw4cpu.h", "yw4fp.h")


def generated_header(cfg: config.Config, src: Path) -> float:
    names = GENERATED_HEADERS + (("yw4load.h",) if src.name == "image_info.c" else ())
    headers = [RUNTIME / "include" / n for n in names] + list((cfg.work_dir / "recomp").glob("*.h"))
    return max(h.stat().st_mtime for h in headers)


def compile_one(cc: str, src: Path, obj: Path, includes: list[str]) -> str | None:
    flags = (MUSL_CFLAGS if MUSL in src.parents else
             [*(CXXFLAGS if src.suffix == ".cpp" else CFLAGS), *target_flags(), *includes])
    proc = subprocess.run([cc, *flags, "-c", str(src), "-o", str(obj)], capture_output=True, text=True)
    if proc.returncode != 0:
        return f"{src.name}:\n{proc.stderr[-2000:]}"
    if proc.stderr.strip():
        print(proc.stderr[-1000:], file=sys.stderr)
    return None


def native_shaders(cfg: config.Config) -> bool:
    """Our own renderer's shaders (runtime/shaders/*.vert, *.frag, *.comp; decision 0024) to SPIR-V in
    work/build/shaders/, where the runtime reads them. Without glslang only a warning: the
    native passes then stay off."""
    from . import shader
    out = cfg.work_dir / "build" / "shaders"
    out.mkdir(parents=True, exist_ok=True)
    exe = shader.glslang(cfg)
    srcs = sorted([*(RUNTIME / "shaders").glob("*.vert"), *(RUNTIME / "shaders").glob("*.frag"),
                   *(RUNTIME / "shaders").glob("*.comp")])
    # shared code the programs #include (*.glsl): a change rebuilds them all
    newest_include = max((p.stat().st_mtime for p in (RUNTIME / "shaders").glob("*.glsl")), default=0)
    for src in srcs:
        spv = out / (src.name + ".spv")
        if spv.exists() and spv.stat().st_mtime >= max(src.stat().st_mtime, newest_include):
            continue
        if not exe:
            print(f"warning: no glslang ([tools] glslang): {src.name} not compiled", file=sys.stderr)
            continue
        r = subprocess.run([exe, "-V", "--target-env", "vulkan1.3", "-o", str(spv), str(src)],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print(f"{src.name}:\n{r.stdout}{r.stderr}", file=sys.stderr)
            return False
        print(f"compiled {src.name}")
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", action="store_true", help="run the result on work/exefs/")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--no-fsr", action="store_true", help="leave out AMD FSR (decision 0039)")
    ap.add_argument("--no-dlss", action="store_true", help="leave out NVIDIA DLSS and Streamline (decision 0040)")
    args = ap.parse_args(argv)
    try:
        cfg = config.load()
    except config.ConfigError as e:
        print(f"config error: {e}", file=sys.stderr)
        return 1
    if not (cfg.work_dir / "recomp" / "image_info.c").is_file():
        print("no generated code; run python -m recomp.translate first", file=sys.stderr)
        return 1

    cc = check.host_cc()
    objdir = cfg.work_dir / "build" / "obj"
    objdir.mkdir(parents=True, exist_ok=True)
    includes = [f"-I{RUNTIME / 'include'}", f"-I{cfg.work_dir / 'recomp'}"]
    # The window (decision 0019): SDL3 (fetched on Windows, the system's elsewhere), Vulkan headers
    includes.append(f"-I{check.REPO / 'third_party' / 'vulkan' / 'include'}")
    includes.append(f"-I{check.REPO / 'third_party' / 'stb'}")  # stb_truetype: the HUD's font (hud.c)
    feature_defs: list[str] = []
    if sys.platform == "win32":
        sdl = deps.fetch_sdl(cfg)
        includes.append(f"-I{sdl / 'include'}")
        sdl_libs = [str(sdl / "lib" / "libSDL3.dll.a")]
        # AMD FSR (decision 0039): headers to compile gpu_fsr.c against, DLLs copied next to yw4.exe below
        if not args.no_fsr:
            fsr = deps.fetch_fsr(cfg) / "Kits" / "FidelityFX"
            includes.append(f"-I{fsr / 'api' / 'include'}")
            feature_defs.append("-DYW4_FSR=1")
        # NVIDIA DLSS (decision 0040): headers, the static NGX library (made for MSVC: runtime/src/msvc_shim.c
        # supplies the few runtime pieces it needs, empty stand-ins satisfy its default-library requests), the DLL
        if not args.no_dlss:
            dlss = deps.fetch_dlss(cfg)
            includes.append(f"-I{dlss / 'include'}")
            feature_defs.append("-DYW4_DLSS=1")
            stub = dlss / "stub"
            if not (stub / "libmsvcprt.a").is_file():
                stub.mkdir(exist_ok=True)
                ar = Path(cc).with_name("llvm-ar.exe")
                for name in ("msvcprt", "OLDNAMES"):
                    subprocess.run([str(ar), "rc", str(stub / f"lib{name}.a")], check=True)
            sdl_libs += [str(dlss / "lib" / "Windows_x86_64" / "x64" / "nvsdk_ngx_d.lib"), f"-L{stub}"]
            # NVIDIA Streamline (DLSS frame generation and Reflex): headers; its DLLs are loaded at run time, copied below
            sl = deps.fetch_streamline(cfg)
            includes.append(f"-I{sl / 'include'}")
            feature_defs.append("-DYW4_STREAMLINE=1")
    else:
        try:
            pc = lambda *a: subprocess.run(["pkg-config", *a, "sdl3"], capture_output=True, text=True, check=True).stdout.split()
            includes += pc("--cflags")
            sdl_libs = pc("--libs")
        except (subprocess.CalledProcessError, FileNotFoundError):
            print("error: SDL3 not found via pkg-config (install sdl3 / libsdl3-dev)", file=sys.stderr)
            return 1
    includes += feature_defs
    hdr = newest_header(cfg)
    # runtime/src/*.h are private to the runtime: changing one doesn't rebuild generated code
    rt_hdr = max([hdr, *(h.stat().st_mtime for h in (RUNTIME / "src").glob("*.h"))])
    musl_hdr = max(h.stat().st_mtime for h in MUSL.rglob("*.h"))
    # other compiler flags than the objects were built with (another YW4_MARCH): everything but musl again
    stamp = objdir / "flags.txt"
    flags_now = " ".join([*CFLAGS, *target_flags()])
    stale_flags = not stamp.exists() or stamp.read_text().strip() != flags_now
    # another set of --no-fsr / --no-dlss: only the runtime's own files read those defines
    feature_stamp = objdir / "features.txt"
    features_now = " ".join(feature_defs)
    stale_features = not feature_stamp.exists() or feature_stamp.read_text().strip() != features_now
    todo, objs = [], []
    for src in sources(cfg):
        rt = src.parent == RUNTIME / "src"
        musl = MUSL in src.parents
        obj = objdir / (("rt_" if rt else "musl_" if musl else "") + src.stem + ".o")
        objs.append(obj)
        dep = musl_hdr if musl else rt_hdr if rt else generated_header(cfg, src)
        if not obj.exists() or obj.stat().st_mtime < max(src.stat().st_mtime, dep) or (stale_flags and not musl) or (stale_features and rt):
            todo.append((src, obj))
    # small generated files, each its own object: a new commit or DLC table recompiles only them
    for gsrc in (version_source(cfg), dlc_source(cfg)):
        gobj = objdir / (gsrc.stem + ".o")
        objs.append(gobj)
        if not gobj.exists() or gobj.stat().st_mtime < gsrc.stat().st_mtime:
            todo.append((gsrc, gobj))
    # The game's icon in the exe (decision 0048): only when tools.yw4.icon made it from the user's own files
    ico = cfg.work_dir / "icon" / "yw4.ico"
    res = objdir / "icon_res.o"
    if sys.platform == "win32" and ico.is_file():
        if not res.exists() or res.stat().st_mtime < ico.stat().st_mtime:
            rc = objdir / "icon.rc"
            rc.write_text(f'1 ICON "{ico.as_posix()}"\n')  # resource 1: Explorer's icon and the window's (window.c)
            r = subprocess.run([str(Path(cc).with_name("llvm-windres.exe")), str(rc), "-O", "coff", "-o", str(res)],
                               capture_output=True, text=True)
            if r.returncode:
                print(f"icon resource failed:\n{r.stderr[-1000:]}", file=sys.stderr)
                return 1
        objs.append(res)
    else:
        res.unlink(missing_ok=True)

    t0 = time.time()
    print(f"compiling {len(todo)} of {len(objs)} files with {Path(cc).name} ({args.jobs} jobs)")
    errors = []
    # Progress counts source bytes, not files: the few biggest generated files take minutes each, so a file count
    # races to the end and then sits there. One log line per finished file, and while nothing finishes, a line every
    # 15 s naming the files still compiling (so a long wait doesn't look like a hang).
    sizes = {src: src.stat().st_size for src, _ in todo}
    total_bytes = sum(sizes.values()) or 1
    started: dict[Path, float] = {}

    def compile_timed(src: Path, obj: Path) -> str | None:
        started[src] = time.time()
        return compile_one(cc, src, obj, includes)

    def took(s: float) -> str:
        return f"{s:.0f} s" if s < 90 else f"{s / 60:.0f} min"

    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        futures = {pool.submit(compile_timed, src, obj): src for src, obj in todo}
        pending, done_n, done_bytes, quiet_since = set(futures), 0, 0, time.time()
        while pending:
            finished, pending = concurrent.futures.wait(pending, timeout=15,
                                                        return_when=concurrent.futures.FIRST_COMPLETED)
            now = time.time()
            for fut in finished:
                src = futures[fut]
                done_n += 1
                done_bytes += sizes[src]
                if fut.result():
                    errors.append(fut.result())
                print(f"{src.name} done ({took(now - started.get(src, t0))}) · {done_n} of {len(todo)}", flush=True)
                progress.report("compile", done_bytes, total_bytes, f"{done_n}/{len(todo)}")
                quiet_since = now
            if pending and now - quiet_since >= 15:
                running = sorted(((now - started[futures[f]], futures[f].name) for f in pending if futures[f] in started),
                                 reverse=True)
                print("still compiling: " + ", ".join(f"{n} ({took(s)})" for s, n in running[:6]), flush=True)
                quiet_since = now
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"{len(errors)} file(s) failed", file=sys.stderr)
        return 1
    stamp.write_text(flags_now + "\n")
    feature_stamp.write_text(features_now + "\n")
    exe = cfg.work_dir / "build" / ("yw4.exe" if sys.platform == "win32" else "yw4")
    # winmm: timeBeginPeriod; gdi32: the game icon read back for the in-game overlay (gamelogo.c); math on Linux
    libs = [*sdl_libs, "-pthread"] + (["-lwinmm", "-lpsapi", "-lgdi32"] if sys.platform == "win32" else ["-lm"])
    if sys.platform == "win32":
        shutil.copy2(sdl / "bin" / "SDL3.dll", exe.parent / "SDL3.dll")  # found next to yw4.exe
        if not args.no_fsr:
            for dll in deps.FSR_DLLS:  # amd_fidelityfx_loader_vk.dll loads the upscaler from its own folder
                shutil.copy2(fsr / "signedbin" / dll, exe.parent / dll)
        else:
            for dll in deps.FSR_DLLS:
                (exe.parent / dll).unlink(missing_ok=True)
        if not args.no_dlss:
            shutil.copy2(dlss / "lib" / "Windows_x86_64" / "rel" / "nvngx_dlss.dll", exe.parent / "nvngx_dlss.dll")
            for dll in deps.SL_DLLS:  # Streamline finds its plugins next to yw4.exe
                shutil.copy2(sl / "bin" / "x64" / dll, exe.parent / dll)
        else:
            (exe.parent / "nvngx_dlss.dll").unlink(missing_ok=True)
            for dll in deps.SL_DLLS:
                (exe.parent / dll).unlink(missing_ok=True)
    progress.report("link", 0, 1)
    print(f"linking {len(objs)} objects into {exe.name}", flush=True)
    t_link = time.time()
    # the ~270 objects go in a response file: in a deep folder (an install path) the command line would pass
    # Windows' 32,767-character limit. Forward slashes and quotes: clang reads it with GNU quoting rules.
    rsp = objdir / "link.rsp"
    rsp.write_text("\n".join(f'"{Path(o).as_posix()}"' for o in objs) + "\n")
    link = subprocess.run([cc, "-o", str(exe), f"@{rsp}", *libs], capture_output=True, text=True)
    progress.report("link", 1, 1)
    if link.returncode != 0:
        print(f"link failed:\n{link.stderr[-3000:]}", file=sys.stderr)
        return 1
    print(f"linked {exe.name} ({time.time() - t_link:.0f} s)")
    print(f"built {exe} in {time.time() - t0:.0f} s")
    if not native_shaders(cfg):
        return 1
    if args.run:
        save = cfg.work_dir / "save"  # the game's save data (the owner's: never commit)
        save.mkdir(exist_ok=True)
        shots = cfg.work_dir / "screenshots"  # F12 / YW4_SCREENSHOTS (images of the game: never commit)
        shots.mkdir(exist_ok=True)
        env = {**os.environ, "YW4_SCREENSHOT_DIR": os.environ.get("YW4_SCREENSHOT_DIR", str(shots))}
        for k, v in cfg.dlc_env().items():  # the owner's DLC folder; the game checks each file (decision 0049)
            env.setdefault(k, v)
        return subprocess.run([str(exe), str(cfg.work_dir / "exefs"), str(cfg.romfs_dir), str(save)], env=env).returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
