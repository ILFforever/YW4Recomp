RUNTIME = check.REPO / "runtime"
CFLAGS = ["-std=c11", "-O2", "-ffp-contract=off", "-Wall", "-Wno-unused-label"]
# The runtime's few C++ files (NVIDIA Streamline's headers are C++): no exceptions or RTTI, so no C++ runtime library
CXXFLAGS = ["-std=c++17", "-O2", "-ffp-contract=off", "-Wall", "-fno-exceptions", "-fno-rtti"]
if sys.platform != "win32":
    # glibc under -std=c11 hides what is POSIX and not ISO C (localtime_r, realpath, setenv, fseeko, off_t, S_IFDIR,
    # ftruncate, strnlen...): 13 runtime files failed on Linux without this (2026-11-12). MinGW shows them anyway.
    CFLAGS.append("-D_GNU_SOURCE")
target_flags = check.target_flags  # the host CPU (decision 0034); musl keeps its verified flags

# musl 1.1.19's math (third_party/musl, decision 0013). These are the flags its results were
# verified with against the sdk (tools/yw4/sdkref.py --check uses this same list): no FMA
# contraction, no builtins (the host must not constant-fold with its own libm).
MUSL = check.REPO / "third_party" / "musl"
MUSL_CFLAGS = ["-std=c99", "-O2", "-ffp-contract=off", "-fno-builtin", "-frounding-math",
               "-include", str(MUSL / "yw4" / "glue.h"), f"-I{MUSL / 'yw4'}", f"-I{MUSL / 'src' / 'internal'}"]


def musl_sources() -> list[Path]:
    return sorted((MUSL / "src" / "math").glob("*.c"))


def sources(cfg: config.Config) -> list[Path]:
    gen = cfg.work_dir / "recomp"
    return (sorted(gen.glob("*.c")) + sorted((RUNTIME / "src").glob("*.c")) + sorted((RUNTIME / "src").glob("*.cpp"))
            + musl_sources())


def version_source(cfg: config.Config) -> Path:
    """<work_dir>/build/version.c: which build this is (decision 0047), rewritten only when it changes so a
    build of the same commit relinks nothing new. The number is the repo's VERSION file; the commit is git's
    (+dirty with uncommitted changes to tracked files), else a COMMIT file (a release download has no git),
    else "unknown"."""
    repo = check.REPO
    version = (repo / "VERSION").read_text().strip()
    commit = "unknown"
    try:
        run = lambda *a: subprocess.run(["git", "-C", str(repo), *a], capture_output=True, text=True, check=True).stdout
        commit = run("rev-parse", "--short=7", "HEAD").strip()
        if run("status", "--porcelain", "--untracked-files=no").strip():
            commit += "+dirty"
    except (OSError, subprocess.CalledProcessError):
        if (repo / "COMMIT").is_file():
            commit = (repo / "COMMIT").read_text().strip() or "unknown"
    day = time.strftime("%Y-%m-%d", time.gmtime())
    text = ("/* Generated by recomp.build (decision 0047). */\n"
            f'const char yw4_version[] = "{version}";\n'
            f'const char yw4_git_commit[] = "{commit}";\n'
            f'const char yw4_build_date[] = "{day}";\n')
    src = cfg.work_dir / "build" / "version.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    if not src.is_file() or src.read_text() != text:
        src.write_text(text)
    print(f"YW4 Recomp {version} ({commit}, {day})")
    return src


def dlc_source(cfg: config.Config) -> Path:
    """<work_dir>/build/dlc_known.c: target.toml's [dlc] table, the add-ons the game unlocks when it finds their
    content NCA on boot (decision 0049; runtime/src/svc_misc.c). Rewritten only when it changes."""
    table = tomllib.loads((check.REPO / "target.toml").read_text()).get("dlc", {})
    rows = "".join(f'    {{{int(i)}, "{h.lower()}"}},\n' for i, h in sorted(table.items(), key=lambda kv: int(kv[0])))
    rows = rows or '    {0, ""},\n'  # C needs one element
    text = ("/* Generated by recomp.build from target.toml [dlc] (decision 0049). */\n#include <stddef.h>\n"
            f'#include "{(RUNTIME / "src" / "dlc_known.h").as_posix()}"\n'
            "const Yw4DlcKnown yw4_dlc_known[] = {\n" + rows + "};\n"
            f"const size_t yw4_ndlc_known = {len(table)};\n")
    src = cfg.work_dir / "build" / "dlc_known.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    if not src.is_file() or src.read_text() != text:
        src.write_text(text)
    return src


def wheel_icons_source(cfg: config.Config) -> Path:
    """<work_dir>/build/wheel_icons.c: the shortcut wheel's icons (decision 0075), game pictures taken from the
    player's own files by tools.yw4.wheel_icons into <work_dir>/wheel/icons.bin (rule 1: never in the repo, as the
    exe's icon, decision 0048). Without that file yw4_wheel_icon returns NULL and the wheel draws arrows. Rewritten
    only when it changes."""
    data = cfg.work_dir / "wheel" / "icons.bin"
    head = "/* Generated by recomp.build (decision 0075). */\n#include <stddef.h>\n#include <stdint.h>\n"
    body = "const uint8_t *yw4_wheel_icon(int slot, int *w, int *h) { (void)slot, (void)w, (void)h; return NULL; }\n"
    if data.is_file():
        raw = data.read_bytes()
        icons, off = [], 8
        if raw[:8] == b"YW4WHEEL":
            for _ in range(8):
                w, h = int.from_bytes(raw[off:off + 2], "little"), int.from_bytes(raw[off + 2:off + 4], "little")
                icons.append((w, h, raw[off + 4:off + 4 + w * h * 4]))
                off += 4 + w * h * 4
        if len(icons) == 8 and all(len(px) == w * h * 4 and w and h for w, h, px in icons):
            arrays = "".join(f"static const uint8_t icon{i}[] = {{{','.join(map(str, px))}}};\n"
                             for i, (w, h, px) in enumerate(icons))
            table = ",".join(f"{{icon{i}, {w}, {h}}}" for i, (w, h, px) in enumerate(icons))
            body = (arrays + "static const struct { const uint8_t *px; int w, h; } icons[8] = {" + table + "};\n"
                    "const uint8_t *yw4_wheel_icon(int slot, int *w, int *h) {\n"
                    "    if (slot < 1 || slot > 8) return NULL;\n"
                    "    *w = icons[slot - 1].w, *h = icons[slot - 1].h;\n"
                    "    return icons[slot - 1].px;\n}\n")
        else:
            print(f"wheel icons: {data} is not a wheel icon file; the wheel draws arrows", file=sys.stderr)
    text = head + body
    src = cfg.work_dir / "build" / "wheel_icons.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    if not src.is_file() or src.read_text() != text:
        src.write_text(text)
    return src


def newest_header(cfg: config.Config) -> float:
    headers = list((RUNTIME / "include").glob("*.h")) + list((cfg.work_dir / "recomp").glob("*.h"))
    return max(h.stat().st_mtime for h in headers)


# What generated code includes: funcs.h -> yw4rt.h -> yw4cpu.h -> yw4fp.h, and yw4load.h for
# image_info.c only. Other runtime headers changing doesn't rebuild the ~150 generated files.
GENERATED_HEADERS = ("yw4rt.h", "yw4cpu.h", "yw4fp.h")


def generated_header(cfg: config.Config, src: Path) -> float:
    names = GENERATED_HEADERS + (("yw4load.h",) if src.name == "image_info.c" else ())
    headers = [RUNTIME / "include" / n for n in names] + list((cfg.work_dir / "recomp").glob("*.h"))
    return max(h.stat().st_mtime for h in headers)


# How long each file takes to compile, so the slowest start first. Handed out in name order, the few generated files
# that take minutes (main_062, main_069, main_070) started late and ran alone at the end: the Linux tester's build
# spent its last 4-5 of 7 minutes on them with the other cores idle (2026-11-13). A file's cost is its own time from
# the last build here (<objdir>/compile_times.json), else the time measured on the owner's PC that ships with the
# code (recomp/compile_cost.json: generated files' names and seconds only, measured at translate.py's CHUNK), else
# a guess from its size.
COST_TABLE = Path(__file__).with_name("compile_cost.json")


def free_memory() -> int | None:
    """Bytes of memory free for new work now (Linux MemAvailable, Windows' available physical memory); None: unknown."""
    try:
        if sys.platform == "win32":
            import ctypes

            class Status(ctypes.Structure):
                _fields_ = [("length", ctypes.c_ulong), ("load", ctypes.c_ulong), ("total", ctypes.c_ulonglong),
                            ("avail", ctypes.c_ulonglong), ("page_total", ctypes.c_ulonglong),
                            ("page_avail", ctypes.c_ulonglong), ("virt_total", ctypes.c_ulonglong),
                            ("virt_avail", ctypes.c_ulonglong), ("ext", ctypes.c_ulonglong)]
            s = Status(length=ctypes.sizeof(Status))
            return int(s.avail) if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(s)) else None
        for line in Path("/proc/meminfo").read_text().splitlines():
            if line.startswith("MemAvailable:"):
                return int(line.split()[1]) * 1024
    except (OSError, ValueError, AttributeError):
        pass
    return None


RESERVE_GB = 1.0  # memory a compile never starts into: left for the rest of the PC


def compile_memory(seconds: float) -> float:
    """A compiler's peak memory (GB) for a file that takes `seconds`: it grows with the file. Measured 2026-11-20 with
    zig and gcc: main_351 (194 s here) 0.8-1.0 GB, an ordinary generated file 0.15-0.22 GB."""
    return 0.25 + 0.85 * min(1.0, seconds / 200)


def load_times(path: Path) -> dict[str, float]:
    try:
        return {k: float(v) for k, v in json.loads(path.read_text()).items()}
    except (OSError, ValueError, AttributeError):
        return {}


def compile_one(cc: str, src: Path, obj: Path, includes: list[str]) -> str | None:
    flags = (MUSL_CFLAGS if MUSL in src.parents else
             [*(CXXFLAGS if src.suffix == ".cpp" else CFLAGS), *target_flags(), *includes])
    proc = subprocess.run([cc, *flags, "-c", str(src), "-o", str(obj)], capture_output=True, text=True)
    if proc.returncode != 0:
        return f"{src.name}:\n{proc.stderr[-2000:]}"
    if proc.stderr.strip():
        print(proc.stderr[-1000:], file=sys.stderr)
    return None


def native_shaders(cfg: config.Config) -> bool:
    """Our own renderer's shaders (runtime/shaders/*.vert, *.frag, *.comp; decision 0024) to SPIR-V in
    work/build/shaders/, where the runtime reads them. Without glslang only a warning: the
    native passes then stay off."""
    from . import shader
    out = cfg.work_dir / "build" / "shaders"
    out.mkdir(parents=True, exist_ok=True)
    exe = shader.glslang(cfg)
    srcs = sorted([*(RUNTIME / "shaders").glob("*.vert"), *(RUNTIME / "shaders").glob("*.frag"),
                   *(RUNTIME / "shaders").glob("*.comp")])
    # shared code the programs #include (*.glsl): a change rebuilds them all
    newest_include = max((p.stat().st_mtime for p in (RUNTIME / "shaders").glob("*.glsl")), default=0)
    for src in srcs:
        spv = out / (src.name + ".spv")
        if spv.exists() and spv.stat().st_mtime >= max(src.stat().st_mtime, newest_include):
            continue
        if not exe:
            print(f"warning: no glslang ([tools] glslang): {src.name} not compiled", file=sys.stderr)
            continue
        r = subprocess.run([exe, "-V", "--target-env", "vulkan1.3", "-o", str(spv), str(src)],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print(f"{src.name}:\n{r.stdout}{r.stderr}", file=sys.stderr)
            return False
        print(f"compiled {src.name}")
    return True


DEV_INI_HEADER = "# Written by recomp.build from config.local.toml"


def dev_game_ini(cfg: config.Config) -> None:
    """<work_dir>/build/game.ini, so `yw4` with no arguments starts the game from this config's folders (decision
    0050's file): the game files, both DLC folders and the manual, which a bare `yw4 <exefs> <romfs>` run doesn't know.
    A launcher install writes its own game.ini after the build (tools/yw4/build_install.py); that one is left alone."""
    ini = cfg.work_dir / "build" / "game.ini"
    if ini.is_file() and not ini.read_text(errors="replace").startswith(DEV_INI_HEADER):
        return
    lines = [f"{DEV_INI_HEADER}; rebuilt on every build. Run yw4 with no arguments to use it.",
             f"YW4_EXEFS={(cfg.work_dir / 'exefs').resolve().as_posix()}",
             f"YW4_ROMFS={cfg.romfs_dir.resolve().as_posix()}"]
    lines += [f"{k}={Path(v).resolve().as_posix()}" for k, v in cfg.dlc_env().items()]
    if (cfg.work_dir / "manual").is_dir():  # the title screen's Manual (python -m tools.yw4.manual)
        lines.append(f"YW4_MANUAL_DIR={(cfg.work_dir / 'manual').resolve().as_posix()}")
    ini.write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", action="store_true", help="run the result on work/exefs/")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--no-fsr", action="store_true", help="leave out AMD FSR (decision 0039)")
    ap.add_argument("--no-dlss", action="store_true", help="leave out NVIDIA DLSS and Streamline (decision 0040)")
    ap.add_argument("--no-xess", action="store_true", help="leave out Intel XeSS (decision 0089, Windows)")
    args = ap.parse_args(argv)
    try:
        cfg = config.load()
    except config.ConfigError as e:
        print(f"config error: {e}", file=sys.stderr)
        return 1
    if not (cfg.work_dir / "recomp" / "image_info.c").is_file():
        print("no generated code; run python -m recomp.translate first", file=sys.stderr)
        return 1

    cc = check.host_cc()
    objdir = cfg.work_dir / "build" / "obj"
    objdir.mkdir(parents=True, exist_ok=True)
    includes = [f"-I{RUNTIME / 'include'}", f"-I{cfg.work_dir / 'recomp'}"]
    # The window (decision 0019): SDL3 (fetched on Windows, the system's elsewhere), Vulkan headers
    includes.append(f"-I{check.REPO / 'third_party' / 'vulkan' / 'include'}")
    includes.append(f"-I{check.REPO / 'third_party' / 'stb'}")  # stb_truetype: the HUD's font (hud.c)
    feature_defs: list[str] = []
    if sys.platform == "win32":
        sdl = deps.fetch_sdl(cfg)
        includes.append(f"-I{sdl / 'include'}")
        sdl_libs = [str(sdl / "lib" / "libSDL3.dll.a")]
        # AMD FSR (decision 0039): headers to compile gpu_fsr.c against, DLLs copied next to yw4.exe below
        if not args.no_fsr:
            fsr = deps.fetch_fsr(cfg) / "Kits" / "FidelityFX"
            includes.append(f"-I{fsr / 'api' / 'include'}")
            feature_defs.append("-DYW4_FSR=1")
        # NVIDIA DLSS (decision 0040): headers, the static NGX library (made for MSVC: runtime/src/msvc_shim.c
        # supplies the few runtime pieces it needs, empty stand-ins satisfy its default-library requests), the DLL
        if not args.no_dlss:
            dlss = deps.fetch_dlss(cfg)
            includes.append(f"-I{dlss / 'include'}")
            feature_defs.append("-DYW4_DLSS=1")
            stub = dlss / "stub"
            if not (stub / "libmsvcprt.a").is_file():
                stub.mkdir(exist_ok=True)
                ar = Path(cc).with_name("llvm-ar.exe")
                for name in ("msvcprt", "OLDNAMES"):
                    subprocess.run([str(ar), "rc", str(stub / f"lib{name}.a")], check=True)
            sdl_libs += [str(dlss / "lib" / "Windows_x86_64" / "x64" / "nvsdk_ngx_d.lib"), f"-L{stub}"]
            # NVIDIA Streamline (DLSS frame generation and Reflex): headers; its DLLs are loaded at run time, copied below
            sl = deps.fetch_streamline(cfg)
            includes.append(f"-I{sl / 'include'}")
            feature_defs.append("-DYW4_STREAMLINE=1")
        # Intel XeSS (decision 0089): the Vulkan headers; libxess.dll is loaded at run time, copied below
        if not args.no_xess:
            xess = deps.fetch_xess(cfg)
            includes.append(f"-I{xess / 'inc' / 'xess'}")
            feature_defs.append("-DYW4_XESS=1")
    else:
        # the system's SDL3 (pkg-config) or the launcher's own copy (decisions 0071, 0083: tools/yw4/system.py)
        found = system.sdl3()
        if not found:
            print("error: SDL3 not found (install sdl3 / libsdl3-dev / SDL3-devel)", file=sys.stderr)
            return 1
        sdl_cflags, sdl_libs, sdl_libdir = found
        includes += sdl_cflags
        # NVIDIA DLSS upscaling on Linux (decision 0073): NVIDIA's static NGX library (built with GCC: C++ runtime and
        # dlopen) and its DLSS library, copied next to yw4 below. No frame generation or Reflex: Streamline is Windows only
        cxx_rt = system.cxx_runtime(cc)
        if not args.no_dlss and platform.machine() in ("x86_64", "AMD64") and cxx_rt is None:
            print("dlss: no libstdc++.so.6 on this system, the game is built without DLSS", file=sys.stderr)
        elif not args.no_dlss and platform.machine() in ("x86_64", "AMD64"):
            dlss = deps.fetch_dlss(cfg)
            includes.append(f"-I{dlss / 'include'}")
            feature_defs.append("-DYW4_DLSS=1")
            sdl_libs += [str(dlss / "lib" / "Linux_x86_64" / "libnvsdk_ngx.a"), *cxx_rt, "-ldl"]
        # AMD FSR upscaling on Linux (decision 0073): built from AMD's SDK v1.1.4 source (tools/yw4/fsr_linux.py), its
        # headers here, libamd_fidelityfx_vk.so copied next to yw4 below and opened at run time (dlopen)
        if not args.no_fsr and platform.machine() in ("x86_64", "AMD64"):
            try:
                fsr_linux = fsr_linux_build.fetch_fsr_linux(cfg)
            except (RuntimeError, OSError) as e:  # an optional extra: the game builds without it (TAA in its place)
                print(f"fsr: could not build AMD FSR for Linux, the game is built without it:\n{e}", file=sys.stderr)
            else:
                includes.append(f"-I{fsr_linux / 'include' / 'ffx_api'}")
                feature_defs.append("-DYW4_FSR=1")
                sdl_libs.append("-ldl")
    includes += feature_defs
    hdr = newest_header(cfg)
    # runtime/src/*.h are private to the runtime: changing one doesn't rebuild generated code
    rt_hdr = max([hdr, *(h.stat().st_mtime for h in (RUNTIME / "src").glob("*.h"))])
    musl_hdr = max(h.stat().st_mtime for h in MUSL.rglob("*.h"))
    # other compiler flags than the objects were built with (another YW4_MARCH): everything but musl again
    stamp = objdir / "flags.txt"
    flags_now = " ".join([*CFLAGS, *target_flags()])
    stale_flags = not stamp.exists() or stamp.read_text().strip() != flags_now
    # another set of --no-fsr / --no-dlss: only the runtime's own files read those defines
    feature_stamp = objdir / "features.txt"
    features_now = " ".join(feature_defs)
    stale_features = not feature_stamp.exists() or feature_stamp.read_text().strip() != features_now
    # the runtime's sources by content, not only their times: objects newer than the sources yet built from other ones
    # (another copy of the code, an update unpacked with older file times) were linked as they were, half old, half
    # new (2026-11-11, 0.9.3: "undefined symbol: yw4_read_watch_arm" after "compiling 0 of 285 files")
    source_stamp = objdir / "runtime_sources.txt"
    digest = hashlib.sha1()
    for f in sorted([*(RUNTIME / "src").iterdir(), *(RUNTIME / "include").glob("*.h")]):
        if f.is_file():
            digest.update(f.name.encode() + b"\0" + f.read_bytes())
    sources_now = digest.hexdigest()
    stale_features = stale_features or not source_stamp.exists() or source_stamp.read_text().strip() != sources_now
    todo, objs = [], []
    for src in sources(cfg):
        rt = src.parent == RUNTIME / "src"
        musl = MUSL in src.parents
        obj = objdir / (("rt_" if rt else "musl_" if musl else "") + src.stem + ".o")
        objs.append(obj)
        dep = musl_hdr if musl else rt_hdr if rt else generated_header(cfg, src)
        if not obj.exists() or obj.stat().st_mtime < max(src.stat().st_mtime, dep) or (stale_flags and not musl) or (stale_features and rt):
            todo.append((src, obj))
    # small generated files, each its own object: a new commit or DLC table recompiles only them
    for gsrc in (version_source(cfg), dlc_source(cfg), wheel_icons_source(cfg)):
        gobj = objdir / (gsrc.stem + ".o")
        objs.append(gobj)
        if not gobj.exists() or gobj.stat().st_mtime < gsrc.stat().st_mtime:
            todo.append((gsrc, gobj))
    # Windows resources: the application manifest (runtime/yw4.manifest: UTF-8 as the process's code page, so paths
    # with non-ASCII characters work), and the game's icon (decision 0048) only when tools.yw4.icon made it from the
    # user's own files
    ico = cfg.work_dir / "icon" / "yw4.ico"
    manifest = RUNTIME / "yw4.manifest"
    res = objdir / "icon_res.o"
    if sys.platform == "win32":
        rc = objdir / "icon.rc"
        text = f'1 24 "{manifest.as_posix()}"\n'  # 24 = RT_MANIFEST, 1 = the manifest Windows reads at process start
        if ico.is_file():
            text += f'1 ICON "{ico.as_posix()}"\n'  # resource 1: Explorer's icon and the window's (window.c)
        inputs = [manifest, *([ico] if ico.is_file() else [])]
        windres = Path(cc).with_name("llvm-windres.exe")
        windres = str(windres) if windres.is_file() else shutil.which("llvm-windres") or shutil.which("windres")
        if not windres:  # a compiler without llvm-mingw's tools: the game still builds, without manifest and icon
            print("note: no llvm-windres next to the compiler: yw4.exe gets no manifest (non-ASCII paths fail) "
                  "and no icon", file=sys.stderr)
            res.unlink(missing_ok=True)
        else:
            if (not res.exists() or not rc.is_file() or rc.read_text() != text
                    or res.stat().st_mtime < max(p.stat().st_mtime for p in inputs)):
                rc.write_text(text)
                r = subprocess.run([windres, str(rc), "-O", "coff", "-o", str(res)], capture_output=True, text=True)
                if r.returncode:
                    print(f"resource (manifest, icon) failed:\n{r.stderr[-1000:]}", file=sys.stderr)
                    return 1
            objs.append(res)
    else:
        res.unlink(missing_ok=True)

    times_file = objdir / "compile_times.json"
    measured = {**load_times(COST_TABLE), **load_times(times_file)}
    cost = {src: measured.get(src.name, src.stat().st_size / 1e6 * 8) for src, _ in todo}  # ~8 s per MB
    todo.sort(key=lambda t: cost[t[0]], reverse=True)
    # Memory: started slowest first, a 12-thread PC compiled its 12 heaviest files at once (~1 GB each), and a 7.5 GB
    # Linux PC without swap froze for 20 minutes (2026-11-20). A file starts only while the memory estimates of the files
    # compiling fit in 80% of what was free at the start, and its own estimate in what is free now less RESERVE_GB (the
    # player opened something big meanwhile: the browser, the game); one always runs. A file held back looks again every
    # 2 s (memory others free comes with no signal). The light files still run args.jobs at once.
    free = free_memory()
    budget = free * 0.8 / 1e9 if free else float("inf")
    mem_lock, in_use, held = threading.Condition(), [0.0], [0]
    t0 = time.time()
    print(f"compiling {len(todo)} of {len(objs)} files with {Path(cc).name} ({args.jobs} jobs"
          + (f", within {budget:.1f} GB of memory)" if free else ")"))
    errors = []
    # Progress counts source bytes, not files: the few biggest generated files take minutes each, so a file count
    # races to the end and then sits there. One log line per finished file, and while nothing finishes, a line every
    # 15 s naming the files still compiling (so a long wait doesn't look like a hang).
    sizes = {src: src.stat().st_size for src, _ in todo}
    total_bytes = sum(sizes.values()) or 1
    started: dict[Path, float] = {}
    took_s: dict[str, float] = {}
    # the launcher's files panel (tools/yw4/progress.py, YW4_PROGRESS_FILES): each file's start and end, and how many
    # wait for memory
    progress.file_event("count", len(todo))
    waiting = [0]

    def compile_timed(src: Path, obj: Path) -> str | None:
        need = compile_memory(cost[src])
        with mem_lock:
            waited = False
            while in_use[0] > 0:
                now = free_memory()
                if in_use[0] + need <= budget and (now is None or need <= now / 1e9 - RESERVE_GB):
                    break
                if not waited:
                    waited = True
                    waiting[0] += 1
                    progress.file_event("wait", waiting[0])
                mem_lock.wait(timeout=2)
            if waited:
                waiting[0] -= 1
                progress.file_event("wait", waiting[0])
            held[0] += waited
            in_use[0] += need
        try:
            started[src] = time.time()
            progress.file_event("start", obj.stem, round(cost[src]), src.name)
            r = compile_one(cc, src, obj, includes)
            took_s[src.name] = round(time.time() - started[src], 1)
            return r
        finally:
            progress.file_event("done", obj.stem)
            with mem_lock:
                in_use[0] -= need
                mem_lock.notify_all()

    def took(s: float) -> str:
        return f"{s:.0f} s" if s < 90 else f"{s / 60:.0f} min"

    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        futures = {pool.submit(compile_timed, src, obj): src for src, obj in todo}
        pending, done_n, done_bytes, quiet_since = set(futures), 0, 0, time.time()
        while pending:
            finished, pending = concurrent.futures.wait(pending, timeout=15,
                                                        return_when=concurrent.futures.FIRST_COMPLETED)
            now = time.time()
            for fut in finished:
                src = futures[fut]
                done_n += 1
                done_bytes += sizes[src]
                if fut.result():
                    errors.append(fut.result())
                print(f"{src.name} done ({took(now - started.get(src, t0))}) · {done_n} of {len(todo)}", flush=True)
                progress.report("compile", done_bytes, total_bytes, f"{done_n}/{len(todo)}")
                quiet_since = now
            if pending and now - quiet_since >= 15:
                running = sorted(((now - started[futures[f]], futures[f].name) for f in pending if futures[f] in started),
                                 reverse=True)
                print("still compiling: " + ", ".join(f"{n} ({took(s)})" for s, n in running[:6]), flush=True)
                quiet_since = now
    times_file.write_text(json.dumps({**load_times(times_file), **took_s}, indent=0, sort_keys=True) + "\n")
    print(f"compiled in {time.time() - t0:.0f} s"
          + (f" ({held[0]} files waited for memory)" if held[0] else ""), flush=True)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"{len(errors)} file(s) failed", file=sys.stderr)
        return 1
    stamp.write_text(flags_now + "\n")
    feature_stamp.write_text(features_now + "\n")
    source_stamp.write_text(sources_now + "\n")
    exe = cfg.work_dir / "build" / ("yw4.exe" if sys.platform == "win32" else "yw4")
    # winmm: timeBeginPeriod; gdi32: the game icon read back for the in-game overlay (gamelogo.c); ws2_32: sockets
    # for local play (socket.c); math on Linux
    libs = [*sdl_libs, "-pthread"] + (["-lwinmm", "-lpsapi", "-lgdi32", "-lws2_32"] if sys.platform == "win32" else ["-lm"])
    if sys.platform == "win32":
        shutil.copy2(sdl / "bin" / "SDL3.dll", exe.parent / "SDL3.dll")  # found next to yw4.exe
        if not args.no_fsr:
            for dll in deps.FSR_DLLS:  # amd_fidelityfx_loader_vk.dll loads the upscaler from its own folder
                shutil.copy2(fsr / "signedbin" / dll, exe.parent / dll)
        else:
            for dll in deps.FSR_DLLS:
                (exe.parent / dll).unlink(missing_ok=True)
        if not args.no_dlss:
            shutil.copy2(dlss / "lib" / "Windows_x86_64" / "rel" / "nvngx_dlss.dll", exe.parent / "nvngx_dlss.dll")
            for dll in deps.SL_DLLS:  # Streamline finds its plugins next to yw4.exe
                shutil.copy2(sl / "bin" / "x64" / dll, exe.parent / dll)
        else:
            (exe.parent / "nvngx_dlss.dll").unlink(missing_ok=True)
            for dll in deps.SL_DLLS:
                (exe.parent / dll).unlink(missing_ok=True)
        if not args.no_xess:  # Intel's licence asks for its text alongside the DLL
            shutil.copy2(xess / "bin" / "libxess.dll", exe.parent / "libxess.dll")
            shutil.copy2(xess / "LICENSE.txt", exe.parent / "libxess.license.txt")
        else:
            (exe.parent / "libxess.dll").unlink(missing_ok=True)
            (exe.parent / "libxess.license.txt").unlink(missing_ok=True)
    else:
        # Linux: an SDL3 outside the system's folders (the launcher's own builder/sdl3, decision 0071, or one built by
        # hand) goes next to yw4, which finds it there through its run path ($ORIGIN): no LD_LIBRARY_PATH to set
        libdir = sdl_libdir
        so = Path(libdir) / "libSDL3.so.0" if libdir else None
        if so and so.is_file() and not libdir.startswith(("/usr/", "/lib")):
            (exe.parent / "libSDL3.so.0").unlink(missing_ok=True)
            shutil.copy2(so.resolve(), exe.parent / "libSDL3.so.0")
            libs.append("-Wl,-rpath,$ORIGIN")
        # NGX finds the DLSS library in the folder gpu_dlss.c names: yw4's own
        dlss_so = exe.parent / deps.DLSS_SO
        if "-DYW4_DLSS=1" in feature_defs:
            shutil.copy2(deps.dlss_dir(cfg) / "lib" / "Linux_x86_64" / "rel" / deps.DLSS_SO, dlss_so)
        else:
            dlss_so.unlink(missing_ok=True)
        fsr_so = exe.parent / "libamd_fidelityfx_vk.so"
        if "-DYW4_FSR=1" in feature_defs:
            shutil.copy2(fsr_linux_build.out_dir(cfg) / "lib" / fsr_linux_build.LIB, fsr_so)
        else:
            fsr_so.unlink(missing_ok=True)
    progress.report("link", 0, 1)
    print(f"linking {len(objs)} objects into {exe.name}", flush=True)
    t_link = time.time()
    # the ~270 objects go in a response file: in a deep folder (an install path) the command line would pass
    # Windows' 32,767-character limit. Forward slashes and quotes: clang reads it with GNU quoting rules.
    rsp = objdir / "link.rsp"
    rsp.write_text("\n".join(f'"{Path(o).as_posix()}"' for o in objs) + "\n")
    link = subprocess.run([cc, "-o", str(exe), f"@{rsp}", *libs], capture_output=True, text=True)
    progress.report("link", 1, 1)
    if link.returncode != 0:
        print(f"link failed:\n{link.stderr[-3000:]}", file=sys.stderr)
        return 1
    print(f"linked {exe.name} ({time.time() - t_link:.0f} s)")
    print(f"built {exe} in {time.time() - t0:.0f} s")
    if not native_shaders(cfg):
        return 1
    dev_game_ini(cfg)
    if args.run:
        save = cfg.work_dir / "save"  # the game's save data (the owner's: never commit)
        save.mkdir(exist_ok=True)
        shots = cfg.work_dir / "screenshots"  # F12 / YW4_SCREENSHOTS (images of the game: never commit)
        shots.mkdir(exist_ok=True)
        env = {**os.environ, "YW4_SCREENSHOT_DIR": os.environ.get("YW4_SCREENSHOT_DIR", str(shots))}
        for k, v in cfg.dlc_env().items():  # the owner's DLC folder; the game checks each file (decision 0049)
            env.setdefault(k, v)
        return subprocess.run([str(exe), str(cfg.work_dir / "exefs"), str(cfg.romfs_dir), str(save)], env=env).returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
